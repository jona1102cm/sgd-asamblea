/**
 * GET /api/reports/:id/export
 * Export report as PDF or Excel
 */
router.get('/:id/export', roleMiddleware(ROLES.ADMIN, ROLES.DIRECTOR), (req, res, next) => {
  try {
    const { id } = req.params;
    const { format = 'pdf' } = req.query;

    if (!['pdf', 'excel', 'csv'].includes(format)) {
      return ApiResponse.error(res, 'Formato de exportación inválido', 400);
    }

    logger.info(`Report ${id} exported as ${format} by ${req.user.email}`);

    // Mock export
    res.setHeader('Content-Type', format === 'pdf' ? 'application/pdf' : 'application/octet-stream');
    res.setHeader('Content-Disposition', `attachment; filename="report-${id}.${format}"`);
    res.send(Buffer.from('Mock export data'));
  } catch (err) {
    logger.error('Export report error:', err);
    next(err);
  }
});

